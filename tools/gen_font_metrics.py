"""Write native/src/fontmetrics.h: pygame's own text metrics for its default font, so the C runtime lays text out the same.

    python tools/gen_font_metrics.py > native/src/fontmetrics.h

For every point size pygame can pick (size * 0.6875) it records the font height, ascent and descent, and the advance of
each printable ASCII character as SDL_ttf measures it with hinting.
"""
import os
os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
import pygame

pygame.font.init()
MAXPT = 80
rows = []
for pt in range(1, MAXPT + 1):
    size = 1
    while int(size * 0.6875) < pt:
        size += 1
    f = pygame.font.Font(None, size)
    assert int(size * 0.6875) == pt
    adv = [f.metrics(chr(c))[0][4] for c in range(32, 127)]
    rows.append((pt, f.get_height(), f.get_ascent(), f.size('Ag')[1], adv, [f.size(chr(c))[1] for c in range(32, 127)]))
print("/* generated by tools/gen_font_metrics.py: pygame default font metrics per point size */")
print("#define FM_MAXPT %d" % MAXPT)
print("static const short FM_HEIGHT[FM_MAXPT + 1] = { 0, " + ", ".join(str(r[1]) for r in rows) + " };")
print("static const short FM_ASCENT[FM_MAXPT + 1] = { 0, " + ", ".join(str(r[2]) for r in rows) + " };")
print("static const unsigned char FM_LINEH[FM_MAXPT + 1][95] = {   /* size()[1] of each character: a line is as tall as its lowest glyph needs */\n    { 0 },")
for r in rows:
    print("    { " + ", ".join(str(a) for a in r[5]) + " },")
print("};")
print("static const unsigned char FM_ADV[FM_MAXPT + 1][95] = {\n    { 0 },")
for r in rows:
    print("    { " + ", ".join(str(a) for a in r[4]) + " },")
print("};")
